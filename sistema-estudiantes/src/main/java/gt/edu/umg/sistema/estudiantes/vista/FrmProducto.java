    private void btnNuevoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNuevoActionPerformed
        // TODO add your handling code here:
        try {
            if (txtId.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Selecciona primero un producto de la tabla.",
                    "Sin selección", JOptionPane.WARNING_MESSAGE);
                return;
        }

        Producto p = new Producto();
        p.setIdProducto(Long.parseLong(txtId.getText().trim()));
        p.setCodigo(txtCodigo.getText().trim());
        p.setNombre(txtNombre.getText().trim());
        p.setDescripcion(txtDescripcion.getText().trim());
        p.setPrecioVenta(parseBigDecimal(txtPrecio.getText(), "Precio"));
        p.setStockActual(parseEntero(txtStock.getText(), "Stock"));
        p.setStockMinimo(parseEntero(txtStockMinimo.getText(), "Stock mínimo"));
        p.setActivo(true);

        controller.actualizar(p);

        JOptionPane.showMessageDialog(this, "Producto actualizado con éxito.");
        limpiarCampos();
        refrescarTabla(null, null);

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, e.getMessage(), "Dato inválido", JOptionPane.ERROR_MESSAGE);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage(),
                "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnNuevoActionPerformed

