private void cargarFilaSeleccionada() {
    int fila = jTable1.getSelectedRow();
    if (fila < 0) return;

    txtId.setText(String.valueOf(jTable1.getValueAt(fila, 0)));
    txtCodigo.setText(String.valueOf(jTable1.getValueAt(fila, 1)));
    txtNombre.setText(String.valueOf(jTable1.getValueAt(fila, 2)));
    txtDescripcion.setText(String.valueOf(jTable1.getValueAt(fila, 3)));
    txtPrecio.setText(String.valueOf(jTable1.getValueAt(fila, 4)));
    txtStock.setText(String.valueOf(jTable1.getValueAt(fila, 5)));
    txtStockMinimo.setText(String.valueOf(jTable1.getValueAt(fila, 6)));
}

private void limpiarCampos() {
    txtId.setText("");
    txtCodigo.setText("");
    txtNombre.setText("");
    txtDescripcion.setText("");
    txtPrecio.setText("");
    txtStock.setText("");
    txtStockMinimo.setText("");
}

private BigDecimal parseBigDecimal(String texto, String campo) {
    try {
        return new BigDecimal(texto.trim().isEmpty() ? "0" : texto.trim());
    } catch (NumberFormatException e) {
        throw new NumberFormatException("El campo " + campo + " debe ser numérico.");
    }
}

private Integer parseEntero(String texto, String campo) {
    try {
        return Integer.parseInt(texto.trim().isEmpty() ? "0" : texto.trim());
    } catch (NumberFormatException e) {
        throw new NumberFormatException("El campo " + campo + " debe ser un número entero.");
    }
}

public void refrescarTabla(String codigo, String nombre) {
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("ID");
    model.addColumn("Código");
    model.addColumn("Nombre");
    model.addColumn("Descripción");
    model.addColumn("Precio");
    model.addColumn("Stock");
    model.addColumn("Stock mín.");

    List<Producto> productos = (codigo == null && nombre == null)
            ? controller.getProductos()
            : controller.buscar(codigo, nombre);

    for (Producto p : productos) {
        Object[] fila = new Object[7];
        fila[0] = p.getIdProducto();
        fila[1] = p.getCodigo();
        fila[2] = p.getNombre();
        fila[3] = p.getDescripcion();
        fila[4] = p.getPrecioVenta();
        fila[5] = p.getStockActual();
        fila[6] = p.getStockMinimo();
        model.addRow(fila);
    }
    jTable1.setModel(model);
}
    
